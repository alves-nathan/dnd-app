import { sha256Hex } from '../catalog/catalogBundleDigest';
import type { CatalogSnapshot } from '../catalog/types';
import { CHARACTER_BACKUP_SCHEMA_VERSION, parseCharacterDataBackup } from '../backup/characterBackup';
import { createPortableCatalogAuditSection, validatePortableCatalogAuditSection } from '../backup/portableCatalogBackup';
import type { PortableRestoreDataCheckpoint } from '../backup/portableRestoreSession';
import type { CatalogRuntimePackageRef } from '../storage/catalogPackageRepository';
import { COMPENDIUM_PERSISTENCE_VERSION } from '../storage/compendiumSnapshot';
import { checkAdditiveV3Stage, type AdditiveV3Stage, type AdditiveV3StageContext } from './importV3AdditiveStage';

export const V3_PRESERVATION_SCHEMA = 'dnd-v3-preservation-checkpoint.v1' as const;

export interface V3PreservationInputs {
  stage: AdditiveV3Stage;
  context: AdditiveV3StageContext;
  portableCheckpoint: PortableRestoreDataCheckpoint;
  catalog: CatalogSnapshot;
  runtimeRef: CatalogRuntimePackageRef;
  /** Exact exports generated by the existing repository and character backup APIs. */
  compendiumExport: string;
  characterBackup: string;
}

export interface V3PreservationCheckpoint {
  schemaVersion: typeof V3_PRESERVATION_SCHEMA;
  stageFingerprint: string;
  compendiumFingerprint: string;
  characterBackupFingerprint: string;
  portableCheckpointFingerprint: string;
  runtimeFingerprint: string;
  runtimeRefFingerprint: string;
  runtimeSnapshotId: string;
  counts: { storageItems: number; characters: number; scenarios: number; presets: number; history: number; runtimeEntries: number };
  blockers: string[];
  activation: 'review-required';
  executable: false;
  retirementAuthorized: false;
  fingerprint: string;
}

export interface V3PreservationResult {
  ok: boolean;
  codes: string[];
  checkpoint?: V3PreservationCheckpoint;
}

// Compare JSON data without relying on object property insertion order. Array
// order is intentionally retained. Full SHA-256 binds local evidence, not trust.
const canonical = (value: unknown): unknown => {
  if (Array.isArray(value)) return value.map(canonical);
  if (!value || typeof value !== 'object') return value;
  const record = value as Record<string, unknown>;
  return Object.fromEntries(Object.keys(record).sort().filter(k => record[k] !== undefined).map(k => [k,canonical(record[k])]));
};
const digest = (value: unknown) => sha256Hex(JSON.stringify(canonical(value)));
const same = (a: unknown,b: unknown) => digest(a) === digest(b);
const fail = (...codes: string[]): V3PreservationResult => ({ok:false,codes});
const sortedIds = (ids: Iterable<string>) => [...ids].sort();
const runtimeGraph = (snapshot: CatalogSnapshot) => ({
  snapshotId:snapshot.snapshotId,catalogVersion:snapshot.catalogVersion,bundleSha256:snapshot.bundleSha256,
  manifest:snapshot.manifest,entries:snapshot.entries,registry:[...snapshot.registry],
  entryById:[...snapshot.entryById],categories:snapshot.categories,categoryById:[...snapshot.categoryById],
  dependenciesFrom:[...snapshot.dependenciesFrom],dependenciesTo:[...snapshot.dependenciesTo],
  aliases:[...snapshot.aliases],filterPolicy:snapshot.filterPolicy,readinessProfile:snapshot.readinessProfile
});

/**
 * Read-only bridge between the V3 stage and the existing backup/checkpoint APIs.
 * Never applies a restore, activates a package, or authorizes a migration.
 * Caller must capture all inputs from the same current local state.
 */
export function prepareV3PreservationCheckpoint(input: V3PreservationInputs): V3PreservationResult {
  try {
    const {stage,context,portableCheckpoint,catalog,runtimeRef,compendiumExport,characterBackup} = input;
    if (!checkAdditiveV3Stage(stage,context).ok) return fail('staleOrInvalidStage');
    if (catalog.validation.status !== 'passed' || catalog.snapshotId !== context.runtimeSnapshotId ||
        !same(sortedIds(catalog.registry.keys()),sortedIds(context.runtimeIds)))
      return fail('runtimeInventoryMismatch');
    if (runtimeRef.kind !== 'bundled' && (runtimeRef.kind !== 'stored' || !runtimeRef.packageId.trim()))
      return fail('invalidRuntimeRef');

    const envelope = JSON.parse(compendiumExport);
    if (envelope?.version !== COMPENDIUM_PERSISTENCE_VERSION ||
        !same(envelope.state,context.installed)) return fail('compendiumBackupMismatch');
    const raw = JSON.parse(characterBackup);
    // Older backups remain supported by their existing reader. They cannot be
    // used as evidence of a complete current portable catalog checkpoint.
    if (raw?.schemaVersion !== CHARACTER_BACKUP_SCHEMA_VERSION) return fail('currentCharacterBackupRequired');
    const parsed = parseCharacterDataBackup(characterBackup);
    if (!parsed.ok || !parsed.backup || !parsed.backup.catalogAudit)
      return fail('characterBackupInvalid');
    if (parsed.issues.length) return fail('characterBackupReviewPending');

    const entities = {
      characters:portableCheckpoint.characterStore.characters,
      scenarios:portableCheckpoint.scenarios,buildPresets:portableCheckpoint.buildPresets,
      buildHistorySnapshots:portableCheckpoint.buildHistorySnapshots
    };
    for (const rows of Object.values(entities)) {
      const ids = rows.map(r => r.id);
      if (ids.some(id => typeof id !== 'string' || !id.trim()) || new Set(ids).size !== ids.length)
        return fail('duplicateOrInvalidPortableIdentity');
    }
    if (!same(raw.entities,entities) || !same(parsed.backup.entities,entities))
      return fail('characterBackupCoverageMismatch');

    const audit = parsed.backup.catalogAudit;
    const expected = createPortableCatalogAuditSection({
      snapshot:catalog,filterState:portableCheckpoint.catalog.filterState,
      revision:portableCheckpoint.catalog.revision,history:portableCheckpoint.catalog.history,
      remediationPlans:portableCheckpoint.characterStore.compatibilityRemediationPlans,
      now:() => new Date(audit.exportedAt)
    });
    const checked = validatePortableCatalogAuditSection({
      candidate:audit,snapshot:catalog,fallback:portableCheckpoint.catalog.filterState,
      knownCharacterIds:entities.characters.map(c => c.id)
    });
    if (!checked.ok || checked.issues.length || !checked.section ||
        !same(audit,expected) || !same(audit,checked.section))
      return fail('catalogBackupCoverageMismatch');

    const body: Omit<V3PreservationCheckpoint,'fingerprint'> = {
      schemaVersion:V3_PRESERVATION_SCHEMA,stageFingerprint:stage.fingerprint,
      compendiumFingerprint:sha256Hex(compendiumExport),characterBackupFingerprint:sha256Hex(characterBackup),
      portableCheckpointFingerprint:digest(portableCheckpoint),runtimeFingerprint:digest(runtimeGraph(catalog)),
      runtimeRefFingerprint:digest(runtimeRef),runtimeSnapshotId:catalog.snapshotId,
      counts:{storageItems:context.installed.items.length,characters:entities.characters.length,
        scenarios:entities.scenarios.length,presets:entities.buildPresets.length,
        history:entities.buildHistorySnapshots.length,runtimeEntries:catalog.registry.size},
      blockers:['mechanicalParityNotApproved','historicalAndInstalledInventoryNotVerified',
        'durableFullCheckpointNotVerified','runtimePackageBytesAndTrustNotVerified',
        'productionTransactionAndRollbackNotVerified','explicitCutoverApprovalMissing'],
      activation:'review-required',executable:false,retirementAuthorized:false
    };
    return {ok:true,codes:[],checkpoint:{...body,fingerprint:digest(body)}};
  } catch {
    return fail('preservationPreparationFailed');
  }
}

/** Revalidation compares a freshly captured state against the manifest.
 * A matching checkpoint is still non-executable. */
export function checkV3PreservationCheckpoint(checkpoint: V3PreservationCheckpoint,input: V3PreservationInputs): {ok:boolean; executable:false} {
  try {
    const next = prepareV3PreservationCheckpoint(input);
    return {ok:!!next.checkpoint && same(checkpoint,next.checkpoint),executable:false};
  } catch {
    return {ok:false,executable:false};
  }
}
